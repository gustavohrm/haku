pub mod commands;
pub mod events;

use tauri_specta::{collect_commands, collect_events, Builder};

use events::{AddressFocusRequested, ExtensionsChanged, MemoryChanged, SettingsChanged, StateChanged};

/// The single description of Haku's IPC surface.
///
/// Both the running application and the binding generator read from here, so
/// the TypeScript the interface imports cannot describe a command that Rust
/// does not have.
pub fn builder() -> Builder<tauri::Wry> {
    Builder::<tauri::Wry>::new()
        .commands(collect_commands![
            commands::get_state,
            commands::get_settings,
            commands::set_settings,
            commands::apply_preset,
            commands::current_preset,
            commands::open_tab,
            commands::close_tab,
            commands::select_tab,
            commands::navigate_tab,
            commands::go_back,
            commands::go_forward,
            commands::reload_tab,
            commands::set_tab_fixed,
            commands::reorder_tab,
            commands::set_layout,
            commands::recent_history,
            commands::clear_history,
            commands::open_tab_devtools,
            commands::answer_dialog,
            commands::memory_report,
            commands::tab_preview,
            commands::extensions,
            commands::open_extensions_folder,
            commands::open_extension_popup,
        ])
        .events(collect_events![
            StateChanged,
            SettingsChanged,
            MemoryChanged,
            AddressFocusRequested,
            ExtensionsChanged
        ])
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Regenerates `src/bindings.ts`.
    ///
    /// A test rather than a build script so that generation is explicit and
    /// cannot silently rewrite the interface's types during an unrelated build.
    /// Run it with `pnpm bindings`.
    #[test]
    fn export_bindings() {
        builder()
            .export(
                specta_typescript::Typescript::default().header("// Generated by `pnpm bindings`. Do not edit.\n"),
                "../src/bindings.ts",
            )
            .expect("failed to write TypeScript bindings");
    }

    /// Every registered command calls `ensure_chrome` as its first statement.
    ///
    /// Tauri allows app commands to any webview whose origin it treats as
    /// local, so this guard is what keeps content webviews out (issue #38).
    #[test]
    fn every_command_guards_with_ensure_chrome() {
        let registry = include_str!("mod.rs");
        let list = registry
            .split("collect_commands![")
            .nth(1)
            .and_then(|rest| rest.split(']').next())
            .expect("collect_commands! list not found");
        let registered: Vec<&str> = list
            .split(',')
            .map(str::trim)
            .filter(|name| !name.is_empty())
            .map(|name| {
                name.strip_prefix("commands::")
                    .expect("command registered from outside commands.rs")
            })
            .collect();
        assert!(!registered.is_empty(), "no registered commands found");

        let source = include_str!("commands.rs");
        let defined: Vec<(&str, &str)> = source
            .split("#[tauri::command]")
            .skip(1)
            .map(|chunk| {
                let name = chunk
                    .split("fn ")
                    .nth(1)
                    .and_then(|rest| rest.split(['(', '<']).next())
                    .expect("command without a function")
                    .trim();
                let body = chunk
                    .split_once('{')
                    .map(|(_, body)| body)
                    .expect("command without a body");
                let first = body.split(';').next().unwrap_or_default();
                (name, first)
            })
            .collect();

        for name in registered {
            let Some((_, first)) = defined.iter().find(|(defined, _)| *defined == name) else {
                panic!("{name} is registered but not defined with #[tauri::command] in commands.rs");
            };
            assert!(
                first.contains("ensure_chrome(&webview)?"),
                "{name} must call `ensure_chrome(&webview)?` before anything else"
            );
        }
    }
}
